'use strict';
const {test,expect}=require('@playwright/test');
test('loginpagina en presentatie-koppelcode openen zonder browserfout',async({browser})=>{
 const context=await browser.newContext();
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 const base=process.env.E2E_BASE_URL||'http://127.0.0.1:3785';
 await page.goto(base+'/');
 await expect(page.locator('#loginForm')).toBeVisible();
 await expect(page.locator('#email')).toBeVisible();
 await expect(page.locator('#password')).toBeVisible();
 const player=await context.newPage();
 player.on('pageerror',e=>errors.push(String(e)));
 await player.goto(base+'/player');
 await expect(player.locator('#pairCodeDisplay')).toHaveText(/^[A-HJ-NP-Z2-9]{10}$/,{timeout:25000});
 expect(errors).toEqual([]);
 await context.close();
});

test('Hoofdbeheer, bedrijf en scherm doorlopen de volledige koppeling',async({browser})=>{
 const adminEmail=process.env.E2E_ADMIN_EMAIL,adminPassword=process.env.E2E_ADMIN_PASSWORD;
 if(!adminEmail||!adminPassword)throw Error('CI testaccounts ontbreken.');
 const base=process.env.E2E_BASE_URL||'http://127.0.0.1:3785';
 const ownerEmail='test-'+Date.now()+'@example.test',ownerPassword='ValidPass-'+Date.now()+'-ABC';
 const owner=await browser.newContext(),page=await owner.newPage();
 await page.goto(base+'/');
 await page.locator('#email').fill(adminEmail);
 await page.locator('#password').fill(adminPassword);
 await page.locator('#loginForm button[type=submit]').click();
 await expect(page.locator('#adminArea')).toBeVisible();
 await page.locator('#addOrgBtn').click();
 await page.locator('#dialogFields [name=name]').fill('Testorganisatie');
 await page.locator('#dialogFields [name=email]').fill(ownerEmail);
 await page.locator('#dialogFields [name=password]').fill(ownerPassword);
 await page.locator('#dialogSubmit').click();
 await expect(page.locator('#newCredentials')).toBeVisible();
 await page.locator('#logout').click();
 await page.locator('#email').fill(ownerEmail);
 await page.locator('#password').fill(ownerPassword);
 await page.locator('#loginForm button[type=submit]').click();
 await expect(page.locator('#companyArea')).toBeVisible();
 await page.locator('#addScreenBtn').click();
 await page.locator('#dialogFields [name=name]').fill('Testscherm');
 await page.locator('#dialogSubmit').click();
 await expect(page.locator('#screenPanel')).toBeVisible();
 const second=await browser.newContext(),player=await second.newPage();
 await player.goto(base+'/player');
 await expect(player.locator('#pairCodeDisplay')).toHaveText(/^[A-HJ-NP-Z2-9]{10}$/,{timeout:25000});
 await page.locator('#pairCode').fill((await player.locator('#pairCodeDisplay').innerText()).trim());
 await page.locator('#pairForm button[type=submit]').click();
 await expect(player.locator('#screenLabel')).toContainText('Testscherm',{timeout:25000});
 await page.locator('#textTitle').fill('Welkom');
 await page.locator('#textBody').fill('Presentatie werkt.');
 await page.locator('#textForm button[type=submit]').click();
 await expect(player.locator('#slide')).toContainText('Presentatie werkt.',{timeout:30000});
 await second.close();await owner.close();
});
